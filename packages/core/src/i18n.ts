/**
 * Minimal i18n: en / zh-CN dictionaries with parameter interpolation.
 * Round-15: fresh installs default to ENGLISH; Chinese is a user switch; the
 * choice persists across restart and upgrade (stored in settings).
 */

export type Locale = 'zh' | 'en';

/** Normalize any persisted locale value to our supported set.
 *  zh, zh-CN, zh_CN, zh-cn -> 'zh'; anything else (or missing) -> 'en'.
 *  The DEFAULT language of the product is English (round-15). */
export function normalizeLocale(l: unknown): Locale {
  if (typeof l === 'string' && /^zh([-_]CN)?$/i.test(l.trim())) return 'zh';
  return 'en';
}

