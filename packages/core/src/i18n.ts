export function translate(locale: Locale | string, key: string, vars?: Record<string, string | number>): string {
  const dict = normalizeLocale(locale) === 'zh' ? zh : en;
  let s = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export type I18nKey = keyof typeof zh;

export function locales(): Locale[] {
  return ['en', 'zh'];
}
